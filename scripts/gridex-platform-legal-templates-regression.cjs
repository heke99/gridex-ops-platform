#!/usr/bin/env node
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

const page = read('app/admin/platform/legal-templates/page.tsx')
const actions = read('app/admin/platform/legal-templates/actions.ts')
const lib = read('lib/legal/platformLegalTemplates.ts')
const defaults = read('lib/tenant/legalDefaults.ts')
const modules = read('lib/legal/canonicalModules.ts')
const migration = read('supabase/migrations/20260716183000_contract_canonical_finalization.sql')

assert(page.includes('Master legal templates'), 'template editor page should render master legal templates title')
assert(page.includes('Validate canonical master templates for tenants'), 'page should validate canonical tenant coverage without copies')
assert(page.includes('TemplatePreview'), 'page should include rendered placeholder preview')
assert(actions.includes('gridex_update_draft_legal_template_version'), 'actions should support canonical draft-only edits')
assert(actions.includes('gridex_publish_legal_template_version'), 'actions should publish immutable canonical template versions')
assert(actions.includes('copyPublishedTemplatesToCompanies'), 'actions should validate canonical coverage for many tenants')
assert(!actions.includes("from('platform_default_legal_templates')"), 'actions must not write the legacy platform template table')
assert(lib.includes('renderTenantLegalTemplate'), 'library should render tenant placeholders')
assert(lib.includes('canonical_legal_template_versions_v'), 'library should read canonical template versions')
assert(!lib.includes('ensurePublishedLegalBundleForCompany'), 'library must not create legacy legal bundles')
assert(lib.includes('company_name') && lib.includes('org_number') && lib.includes('support_email'), 'renderer should support required placeholders')
assert(defaults.includes("source: 'canonical_platform_template_validation'"), 'company default validation should use canonical templates')
assert(modules.includes('quarterly_price_terms') && modules.includes('production_terms') && modules.includes('authorized_signatory'), 'canonical module catalog should cover dynamic legal variants')
assert(migration.includes('gridex_create_legal_template_version'), 'migration should expose canonical template version RPC')
assert(migration.includes('gridex_create_tenant_legal_override'), 'migration should expose tenant override RPC')
assert(migration.includes("'origin','platform_template'"), 'canonical view should expose legal provenance')

console.log('Platform legal templates regression passed')
