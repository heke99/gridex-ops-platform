'use strict'
const assert = require('node:assert/strict')
const { normalizeDump, prepareRestore, RESTRICT_TOKEN } = require('./gridex-schema-dump.cjs')
const fs = require('node:fs')
const body = "SET statement_timeout = 0;\nCREATE FUNCTION public.demo() RETURNS text LANGUAGE sql AS $body$\nSELECT $value$first\n\n\n-- Dumped by pg_dump version must stay inside the literal\n\\restrict insideBody\nlast$value$;\n$body$;\n\n\n"
const source = `-- PostgreSQL database dump\n\n\\restrict randomA123\n-- Dumped from database version 17.6\n-- Dumped by pg_dump version 17.11\n\n${body}-- PostgreSQL database dump complete\n\\unrestrict randomA123\n`
const normalized = normalizeDump(source)
assert.match(RESTRICT_TOKEN, /^[A-Za-z0-9]+$/)
assert.ok(normalized.includes(body), 'normalization changed SQL bytes')
assert.ok(!normalized.includes('-- Dumped from database version 17.6'))
assert.ok(normalized.includes('-- Dumped by pg_dump version must stay inside the literal'))
assert.ok(normalized.includes('\\restrict insideBody'))
assert.equal(normalized, normalizeDump(source.replaceAll('randomA123', 'randomB456')))
assert.equal(normalizeDump(normalized), normalized)
const restoredA = prepareRestore(normalized), restoredB = prepareRestore(normalized)
assert.ok(restoredA.includes(body)); assert.ok(restoredB.includes(body))
assert.notEqual(restoredA, restoredB, 'restore keys must be fresh')
const keys = [...restoredA.matchAll(/^\\(?:un)?restrict ([a-f0-9]{64})$/gm)].map(match => match[1])
assert.equal(keys.length, 2); assert.equal(keys[0], keys[1])
assert.throws(() => prepareRestore('SELECT 1;\n'), /requires outer guards/)
assert.throws(() => normalizeDump(source.replace('\\unrestrict randomA123', '\\unrestrict wrong')), /keys disagree/)
assert.throws(() => normalizeDump(source.replace('\\unrestrict randomA123', '')), /incomplete/)
assert.throws(() => normalizeDump('\\restrict key1\n\\restrict key1\nSELECT 1;\n\\unrestrict key1\n'), /incomplete/)
assert.equal(normalizeDump('CREATE TABLE public.demo (id integer);\n'), 'CREATE TABLE public.demo (id integer);\n')
const pinned = fs.readFileSync(require('node:path').join(__dirname, '../supabase/schema.sql'), 'utf8')
const replay = prepareRestore(pinned)
const before = pinned.split('\n'), after = replay.split('\n')
assert.equal(before.length, after.length)
const changed = before.flatMap((line, i) => line !== after[i] ? [i] : [])
assert.equal(changed.length, 2, 'historical restore changed more than two guard lines')
assert.ok(changed.every(i => /^\\(?:un)?restrict /.test(before[i])))
assert.equal(normalizeDump(pinned).includes('\\restrict gridex_canonical_schema_snapshot'), false)
console.log('PASS schema dump normalization: valid keys, exact SQL bodies, fresh restore keys, rejection controls')
